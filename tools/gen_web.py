#!/usr/bin/env python3
"""Turns source/index.html into source/web.h so the page is built into the plugin."""
import os

here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "source")
html = open(os.path.join(here, "index.html"), "rb").read()
with open(os.path.join(here, "web.h"), "w") as o:
    o.write("/* generated by tools/gen_web.py - do not edit */\n")
    o.write("static const unsigned char WEB_PAGE[%d] = {\n" % len(html))
    for i in range(0, len(html), 32):
        o.write(",".join(str(b) for b in html[i:i + 32]) + ",\n")
    o.write("};\n")
print("web.h:", len(html), "bytes")
